Page({
  data: {
    // 提示词列表（每项附带 open 展开标志，供 WXML 直接读取）
    prompts: PROMPTS.map(p => Object.assign({}, p, { open: false }))
  },

  // 展开/收起提示词模板
  onToggle(e) {
    const index = Number(e.currentTarget.dataset.index)
    const key = 'prompts[' + index + '].open'
    this.setData({ [key]: !this.data.prompts[index].open })
  },

  // 复制提示词到剪贴板
  onCopy(e) {
    const index = Number(e.currentTarget.dataset.index)
    const item = this.data.prompts[index]
    if (!item) return
    api.copyText(item.content)
      .then(() => wx.showToast({ title: '已复制提示词', icon: 'none' }))
      .catch(() => wx.showToast({ title: '复制失败', icon: 'none' }))
  }
})
